"""The original-cry marker: which strata_<folder>.wav files gen_cry.py wrote.

sound/direct_sound_samples/cries/strata_cries.txt lists one generated cry per
line (folder, SHA-1 of the wav, plan, seconds). gen_species.py keeps a species'
wav if it is listed and the hash still matches, and otherwise copies the
`borrow=` stock cry as a placeholder (an error once CRY_STRICT is on).
gen_sprite.py --borrowed reports the count from here. Stdlib only: imported by
gen_species.py and sprites/check.py.
"""

import hashlib
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
CRY_DIR = os.path.join(ROOT, "sound/direct_sound_samples/cries")
MANIFEST = os.path.join(CRY_DIR, "strata_cries.txt")
HEADER = ("# Original Strata cries, generated by tools/strata/gen_cry.py: do not edit.\n"
          "# folder  sha1(wav)  plan  seconds  (gen_species.py keeps listed wavs whose hash matches)\n")


def wav_path(folder):
    return os.path.join(CRY_DIR, f"strata_{folder}.wav")


def sha1(path):
    with open(path, "rb") as f:
        return hashlib.sha1(f.read()).hexdigest()


def read():
    """folder -> (sha1, plan, seconds) for every listed cry."""
    out = {}
    if not os.path.exists(MANIFEST):
        return out
    with open(MANIFEST) as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            folder, digest, plan, secs = line.split()[:4]
            out[folder] = (digest, plan, float(secs))
    return out


def write(entries, order):
    """entries: folder -> (sha1, plan, seconds); written in `order` (roster order)."""
    with open(MANIFEST, "w") as f:
        f.write(HEADER)
        for folder in order:
            if folder in entries:
                d, plan, secs = entries[folder]
                f.write(f"{folder} {d} {plan} {secs:.3f}\n")


def original(folder, listed=None):
    """True if folder's wav is a generated original cry (listed, hash matches)."""
    listed = read() if listed is None else listed
    if folder not in listed or not os.path.exists(wav_path(folder)):
        return False
    return sha1(wav_path(folder)) == listed[folder][0]


def status(folders):
    """(original, borrowed, stale): stale = listed but the wav changed since."""
    listed = read()
    own, borrowed, stale = [], [], []
    for f in folders:
        if original(f, listed):
            own.append(f)
        else:
            borrowed.append(f)
            if f in listed:
                stale.append(f)
    return own, borrowed, stale
