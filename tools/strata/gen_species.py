#!/usr/bin/env python3
"""Generate Strata species data from tools/strata/roster.py.

Usage (from the repo root):  python3 tools/strata/gen_species.py

Writes:
  include/constants/species.h                 SPECIES_* constants      } between
  include/constants/pokedex.h                 NATIONAL_DEX_* constants } BEGIN/END STRATA
  include/constants/cries.h                   CRY_* constants          } marker comments
  sound/cry_tables.inc                        cry table entries        }
  sound/direct_sound_data.inc                 cry samples              }
  src/data/pokemon/species_info/strata_families.h
  src/data/pokemon/level_up_learnsets/strata.h
  src/data/graphics/strata_pokemon.h
  graphics/pokemon/strata/<name>/             sprites copied from the borrowed species, unless the
                                              folder has a CUSTOM marker (own art from gen_sprite.py,
                                              whose presentation fields override the borrowed ones)
  sound/direct_sound_samples/cries/strata_<name>.wav   cry copied from the borrowed species

Strata species own copies of everything they borrow, so they keep working when
the stock generations are disabled in include/config/species_enabled.h.

Stats are grounded in body mass. The base stat total is
    BST = 300 + 70 * log10(mass in kg), clamped to [180, 600]
so a 50 g Mesodma gets ~209 and an 8 t Tyrannosaurus ~573. Each species'
`weights` then split that total by anatomy (see roster.py).
"""

import math
import os
import re
import shutil
import sys
import textwrap

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.dirname(__file__))
from roster import SPECIES  # noqa: E402

GENERATED = "// DO NOT MODIFY: generated by tools/strata/gen_species.py from tools/strata/roster.py\n"
STAT_KEYS = ["hp", "atk", "defn", "spe", "spa", "spd"]
STAT_FIELDS = {"hp": "baseHP", "atk": "baseAttack", "defn": "baseDefense",
               "spe": "baseSpeed", "spa": "baseSpAttack", "spd": "baseSpDefense"}
EV_FIELDS = {"hp": "evYield_HP", "atk": "evYield_Attack", "defn": "evYield_Defense",
             "spe": "evYield_Speed", "spa": "evYield_SpAttack", "spd": "evYield_SpDefense"}
NAME_LENGTH = 12
CATEGORY_LENGTH = 12
DEX_LINE_WIDTH = 38  # ~224 px in FONT_NORMAL; test/text.c checks the real width
DEX_MAX_LINES = 4
MAX_WEIGHT_HG = 65535

# Graphics/presentation fields copied from the borrowed species' entry.
BORROWED_FIELDS = [
    ".pokemonScale", ".pokemonOffset", ".trainerScale", ".trainerOffset",
    ".frontPicSize", ".frontPicYOffset", ".frontAnimFrames", ".frontAnimId", ".frontAnimDelay",
    ".enemyMonElevation", ".backPicSize", ".backPicYOffset", ".backAnimId", ".iconPalIndex", "SHADOW(",
]
GRAPHIC_FILES = ["anim_front.png", "front.png", "back.png", "normal.pal", "shiny.pal", "icon.png", "footprint.png"]


def die(msg):
    sys.exit(f"gen_species: {msg}")


def const_name(sp):
    return re.sub(r"[^A-Z0-9]", "_", sp["name"].upper())


def symbol_name(sp):
    return re.sub(r"[^A-Za-z0-9]", "", sp["name"])


def folder_name(sp):
    return re.sub(r"[^a-z0-9]", "_", sp["name"].lower())


def base_stat_total(mass):
    return max(180, min(600, round(300 + 70 * math.log10(mass))))


def base_stats(sp):
    bst = base_stat_total(sp["mass"])
    weights = sp["weights"]
    total = sum(weights[k] for k in STAT_KEYS)
    return {k: max(1, min(255, round(bst * weights[k] / total))) for k in STAT_KEYS}, bst


def find_species_block(borrow):
    """Returns the lines of [SPECIES_<borrow>]'s entry in the stock species_info files."""
    pattern = re.compile(r"^\s*\[SPECIES_%s\]\s*=" % re.escape(borrow.upper()))
    info_dir = os.path.join(ROOT, "src/data/pokemon/species_info")
    for fname in sorted(os.listdir(info_dir)):
        if not fname.startswith("gen_"):
            continue
        with open(os.path.join(info_dir, fname)) as f:
            lines = f.read().split("\n")
        for i, line in enumerate(lines):
            if pattern.match(line):
                indent = len(line) - len(line.lstrip())
                end = next(j for j in range(i + 1, len(lines))
                           if lines[j].startswith(" " * indent + "},"))
                return lines[i + 2:end]
    die(f"borrowed species SPECIES_{borrow.upper()} not found")


def borrowed_fields(block, stock_symbol, our_symbol):
    """Copies presentation fields from a stock entry. Takes only the first
    branch of any #if inside the entry, and the first occurrence of each field."""
    out, seen = [], set()
    depth_skip = 0  # >0 while inside an #else/#elif branch we're skipping
    i = 0
    while i < len(block):
        line = block[i]
        stripped = line.strip()
        if stripped.startswith("#if"):
            depth_skip = depth_skip + 1 if depth_skip else 0
            i += 1
            continue
        if stripped.startswith("#else") or stripped.startswith("#elif"):
            depth_skip = max(depth_skip, 1)
            i += 1
            continue
        if stripped.startswith("#endif"):
            depth_skip = max(0, depth_skip - 1)
            i += 1
            continue
        field = next((f for f in BORROWED_FIELDS if stripped.startswith(f)), None)
        if field is None or depth_skip or field in seen:
            i += 1
            continue
        seen.add(field)
        chunk = [line]
        if line.rstrip().endswith("("):  # multi-line macro, closed by a lone "),"
            while chunk[-1].strip() != "),":
                i += 1
                chunk.append(block[i])
        out.extend(c.replace("_" + stock_symbol, "_" + our_symbol) for c in chunk)
        i += 1
    return out


def stock_symbol(block, borrow):
    for line in block:
        m = re.search(r"gMonFrontPic_(\w+)", line)
        if m:
            return m.group(1)
    die(f"no front pic symbol for {borrow}")


def wrap_dex(sp):
    lines = textwrap.wrap(sp["dex"], DEX_LINE_WIDTH)
    if len(lines) > DEX_MAX_LINES:
        die(f"{sp['name']}: dex text needs {len(lines)} lines (max {DEX_MAX_LINES})")
    return lines


def c_string(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def custom_art(sp):
    """Presentation-field overrides if the species has its own art (a CUSTOM
    marker written by gen_sprite.py in its graphics folder), else None."""
    path = os.path.join(ROOT, "graphics/pokemon/strata", folder_name(sp), "CUSTOM")
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return [l.strip() for l in f if l.strip().startswith(".")]


def apply_overrides(fields, overrides):
    """Replaces borrowed `.field = ...,` lines with the custom art's."""
    key = lambda line: line.strip().split("=")[0].strip()  # noqa: E731
    wanted = {key(o): o for o in overrides}
    out = []
    for line in fields:
        k = key(line)
        if k in wanted and line.strip().startswith(k + " "):
            out.append(line[:len(line) - len(line.lstrip())] + wanted.pop(k))
        else:
            out.append(line)
    return out + ["        " + o for o in wanted.values()]


def copy_graphics(sp):
    src = os.path.join(ROOT, "graphics/pokemon", sp["borrow"])
    dst = os.path.join(ROOT, "graphics/pokemon/strata", folder_name(sp))
    os.makedirs(dst, exist_ok=True)
    if custom_art(sp) is not None:  # our own sprites: keep them
        return [f for f in GRAPHIC_FILES if os.path.exists(os.path.join(dst, f))]
    copied = []
    for fname in GRAPHIC_FILES:
        if os.path.exists(os.path.join(src, fname)):
            shutil.copyfile(os.path.join(src, fname), os.path.join(dst, fname))
            copied.append(fname)
    if "anim_front.png" not in copied and "front.png" not in copied:
        die(f"{sp['borrow']} has no front sprite")
    return copied


def cry_symbol(sp):
    return f"Cry_Strata{symbol_name(sp)}"


def cry_file(sp):
    return f"strata_{folder_name(sp)}"


def copy_cry(sp):
    cries = os.path.join(ROOT, "sound/direct_sound_samples/cries")
    src = os.path.join(cries, f"{sp['borrow']}.wav")
    if not os.path.exists(src):
        die(f"{sp['borrow']} has no cry sample")
    shutil.copyfile(src, os.path.join(cries, f"{cry_file(sp)}.wav"))


def gen_cry_sample(sp):
    return ["\t.align 2",
            f"{cry_symbol(sp)}::",
            ".if TESTING == FALSE",
            f'\t.incbin "sound/direct_sound_samples/cries/{cry_file(sp)}.bin"',
            ".endif",
            ""]


def validate(sp):
    if len(sp["name"]) > NAME_LENGTH:
        die(f"name '{sp['name']}' is longer than {NAME_LENGTH}")
    if len(sp["category"]) > CATEGORY_LENGTH:
        die(f"{sp['name']}: category '{sp['category']}' is longer than {CATEGORY_LENGTH}")


def gen_graphics(sp, files):
    sym, folder = symbol_name(sp), f"graphics/pokemon/strata/{folder_name(sp)}"
    front = "anim_front.png" if "anim_front.png" in files else "front.png"
    out = [
        f'const u32 gMonFrontPic_{sym}[] = INCGFX_U32("{folder}/{front}", ".4bpp.smol");',
        f'const u16 gMonPalette_{sym}[] = INCGFX_U16("{folder}/normal.pal", ".gbapal");',
        f'const u32 gMonBackPic_{sym}[] = INCGFX_U32("{folder}/back.png", ".4bpp.smol");',
        f'const u16 gMonShinyPalette_{sym}[] = INCGFX_U16("{folder}/shiny.pal", ".gbapal");',
        f'const u8 gMonIcon_{sym}[] = INCGFX_U8("{folder}/icon.png", ".4bpp");',
    ]
    if "footprint.png" in files:
        out += ["#if P_FOOTPRINTS",
                f'const u8 gMonFootprint_{sym}[] = INCGFX_U8("{folder}/footprint.png", ".1bpp");',
                "#endif //P_FOOTPRINTS"]
    return out


def gen_species_info(sp, files):
    sym, const = symbol_name(sp), const_name(sp)
    stats, bst = base_stats(sp)
    block = find_species_block(sp["borrow"])
    borrowed = borrowed_fields(block, stock_symbol(block, sp["borrow"]), sym)
    top = max(STAT_KEYS, key=lambda k: stats[k])
    ev = 1 if bst < 350 else 2 if bst < 500 else 3
    weight = round(sp["mass"] * 10)
    weight_note = ""
    if weight > MAX_WEIGHT_HG:
        weight_note = f" // TODO: real mass {sp['mass']:g} kg exceeds the u16 weight field"
        weight = MAX_WEIGHT_HG
    abilities = list(sp["abilities"]) + ["NONE"] * (3 - len(sp["abilities"]))
    dex = wrap_dex(sp)

    o = []
    o.append(f"    // {sp['genus']} | {sp['site']} | {sp['age']} | "
             f"{'~' if sp.get('mass_est') else ''}{sp['mass']:g} kg, {sp['length']:g} m | BST {bst}")
    if sp.get("notes"):
        o.append(f"    // Note: {sp['notes']}")
    o.append(f"    [SPECIES_{const}] =")
    o.append("    {")
    for k in STAT_KEYS:
        o.append(f"        .{STAT_FIELDS[k]:<13} = {stats[k]},")
    o.append(f"        .types = MON_TYPES({', '.join('TYPE_' + t for t in sp['types'])}),")
    o.append(f"        .catchRate = {sp['catch']},")
    o.append(f"        .expYield = {round(bst * 0.3)},")
    o.append(f"        .{EV_FIELDS[top]} = {ev},")
    o.append(f"        .genderRatio = PERCENT_FEMALE({sp['gender']}),")
    o.append("        .eggCycles = 20,")
    o.append("        .friendship = STANDARD_FRIENDSHIP,")
    o.append(f"        .growthRate = GROWTH_{sp['growth']},")
    o.append("        .eggGroups = MON_EGG_GROUPS(EGG_GROUP_NO_EGGS_DISCOVERED),")
    o.append(f"        .abilities = {{ {', '.join('ABILITY_' + a for a in abilities)} }},")
    o.append(f"        .bodyColor = BODY_COLOR_{sp['color']},")
    o.append(f'        .speciesName = _("{c_string(sp["name"])}"),')
    o.append(f"        .cryId = CRY_{const},")
    o.append(f"        .natDexNum = NATIONAL_DEX_{const},")
    o.append(f'        .categoryName = _("{c_string(sp["category"])}"),')
    o.append(f"        .height = {max(1, round(sp['length'] * 10))},")
    o.append(f"        .weight = {weight},{weight_note}")
    o.append("        .description = COMPOUND_STRING(")
    for j, line in enumerate(dex):
        nl = "\\n" if j < len(dex) - 1 else ""
        o.append(f'            "{c_string(line)}{nl}"' + (")," if j == len(dex) - 1 else ""))
    o.append(f"        .frontPic = gMonFrontPic_{sym},")
    o.append(f"        .backPic = gMonBackPic_{sym},")
    o.append(f"        .palette = gMonPalette_{sym},")
    o.append(f"        .shinyPalette = gMonShinyPalette_{sym},")
    o.append(f"        .iconSprite = gMonIcon_{sym},")
    overrides = custom_art(sp)
    if overrides is None:
        o.append(f"        // Placeholder presentation borrowed from SPECIES_{sp['borrow'].upper()}")
        o.extend(borrowed)
    else:
        o.append(f"        // Own art (tools/strata/gen_sprite.py); other presentation borrowed from SPECIES_{sp['borrow'].upper()}")
        o.extend(apply_overrides(borrowed, overrides))
    if "footprint.png" in files:
        o.append(f"        FOOTPRINT({sym})")
    o.append(f"        .levelUpLearnset = s{sym}LevelUpLearnset,")
    o.append("    },")
    return o


def gen_learnset(sp):
    sym = symbol_name(sp)
    o = [f"static const struct LevelUpMove s{sym}LevelUpLearnset[] = {{"]
    for level, move in sp["moves"]:
        o.append(f"    LEVEL_UP_MOVE({level:2}, MOVE_{move}),")
    o += ["    LEVEL_UP_END", "};", ""]
    return o


def write(path, lines):
    with open(os.path.join(ROOT, path), "w") as f:
        f.write("\n".join(lines) + "\n")


# The enum headers are also parsed as text by the assembler's preprocessor, which
# can't follow #include, so generated lines are spliced in between marker
# comments: "BEGIN STRATA <tag>" ... "END STRATA <tag>" (any comment syntax).
def splice(path, tag, lines):
    full = os.path.join(ROOT, path)
    with open(full) as f:
        text = f.read().split("\n")
    try:
        begin = next(i for i, l in enumerate(text) if l.rstrip().endswith(f"BEGIN STRATA {tag}"))
        end = next(i for i, l in enumerate(text) if l.rstrip().endswith(f"END STRATA {tag}"))
    except StopIteration:
        die(f"{path} has no BEGIN/END STRATA {tag} markers")
    text[begin + 1:end] = lines
    with open(full, "w") as f:
        f.write("\n".join(text))


def main():
    names = set()
    for sp in SPECIES:
        validate(sp)
        if sp["name"] in names:
            die(f"duplicate species name {sp['name']}")
        names.add(sp["name"])

    species_enum, natdex_enum, cry_enum = [], [], []
    cry_table, cry_table_reverse, cry_samples = [], [], []
    info, learnsets, graphics = [GENERATED], [GENERATED], [GENERATED]
    for sp in SPECIES:
        files = copy_graphics(sp)
        copy_cry(sp)
        species_enum.append(f"    SPECIES_{const_name(sp)},")
        natdex_enum.append(f"    NATIONAL_DEX_{const_name(sp)},")
        cry_enum.append(f"    CRY_{const_name(sp)},")
        cry_table.append(f"\tcry {cry_symbol(sp)}")
        cry_table_reverse.append(f"\tcry_reverse {cry_symbol(sp)}")
        cry_samples += gen_cry_sample(sp)
        info += gen_species_info(sp, files) + [""]
        learnsets += gen_learnset(sp)
        graphics += gen_graphics(sp, files) + [""]

    splice("include/constants/species.h", "SPECIES", species_enum)
    splice("include/constants/pokedex.h", "SPECIES", natdex_enum)
    splice("include/constants/cries.h", "CRIES", cry_enum)
    splice("sound/cry_tables.inc", "CRY_TABLE", cry_table)
    splice("sound/cry_tables.inc", "CRY_TABLE_REVERSE", cry_table_reverse)
    splice("sound/direct_sound_data.inc", "CRY_SAMPLES", cry_samples)
    write("src/data/pokemon/species_info/strata_families.h", info)
    write("src/data/pokemon/level_up_learnsets/strata.h", learnsets)
    write("src/data/graphics/strata_pokemon.h", graphics)

    for sp in SPECIES:
        stats, bst = base_stats(sp)
        print(f"{sp['name']:<13} BST {bst:3}  " + " ".join(f"{k}:{stats[k]:3}" for k in STAT_KEYS))


if __name__ == "__main__":
    main()
