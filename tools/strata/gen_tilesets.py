#!/usr/bin/env python3
"""Generate palette variants of stock tilesets for Strata's eras.

Usage (from the repo root):  python3 tools/strata/gen_tilesets.py

A variant reuses its base tileset's tiles and metatiles and only swaps the
palettes, so a map can show the same kind of place in a different climate.
Writes data/tilesets/<kind>/<variant>/palettes/*.pal and the C definitions in
src/data/tilesets/strata_headers.h (copied from the base's struct in headers.h).
"""

import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
GENERATED = "// DO NOT MODIFY: generated by tools/strata/gen_tilesets.py\n"


def clamp(*rgb):
    return tuple(max(0, min(255, round(c))) for c in rgb)


def lum(r, g, b):
    return 0.30 * r + 0.59 * g + 0.11 * b


def is_green(r, g, b):
    return g > r and g > b


def impact_winter(r, g, b):
    """A year after the impact: soot-darkened and ash-covered. Greens lose
    almost all of their colour."""
    l = lum(r, g, b)
    keep = 0.25 if is_green(r, g, b) else 0.35
    r, g, b = (l + (c - l) * keep for c in (r, g, b))
    return clamp(r * 0.72 + 10, g * 0.70 + 6, b * 0.70 + 4)


def petm(r, g, b):
    """PETM hothouse: warm light, reddened soils, olive vegetation."""
    if is_green(r, g, b):
        r, g, b = r * 1.10 + 12, g * 0.95, b * 0.75
    else:
        r, g, b = r * 1.10 + 8, g * 0.95, b * 0.85
    return clamp(r, g, b)


def oligocene(r, g, b):
    """After the Eocene-Oligocene cooling: drier, paler, yellowed grass."""
    l = lum(r, g, b)
    if is_green(r, g, b):
        r, g, b = r * 1.15 + 18, g * 0.98 + 4, b * 0.70
    r, g, b = (l + (c - l) * 0.80 for c in (r, g, b))
    return clamp(r + 6, g + 4, b)


def ice_age(r, g, b):
    """Glacial steppe: cold light, frost-pale, blue-shifted."""
    l = lum(r, g, b)
    r, g, b = (l + (c - l) * 0.45 for c in (r, g, b))
    return clamp(r * 0.85 + 34, g * 0.90 + 36, b * 0.95 + 52)


TRANSFORMS = {"impact_winter": impact_winter, "petm": petm, "oligocene": oligocene, "ice_age": ice_age}

# variant dir -> (kind, base dir, base symbol suffix, transform)
VARIANTS = {
    "general_winter":      ("primary", "general", "General", "impact_winter"),
    "fortree_winter":      ("secondary", "fortree", "Fortree", "impact_winter"),
    "general_petm":        ("primary", "general", "General", "petm"),
    "fallarbor_petm":      ("secondary", "fallarbor", "Fallarbor", "petm"),
    "general_oligocene":   ("primary", "general", "General", "oligocene"),
    "fallarbor_oligocene": ("secondary", "fallarbor", "Fallarbor", "oligocene"),
    "general_ice_age":     ("primary", "general", "General", "ice_age"),
    "mauville_ice_age":    ("secondary", "mauville", "Mauville", "ice_age"),
}


def symbol_suffix(variant):
    return "".join(part.capitalize() for part in variant.split("_"))


def read_pal(path):
    lines = open(path).read().split()
    count = int(lines[2])
    return [tuple(int(v) for v in lines[3 + i * 3:6 + i * 3]) for i in range(count)]


def write_pal(path, colors):
    with open(path, "w", newline="\r\n") as f:
        f.write("JASC-PAL\n0100\n%d\n" % len(colors))
        f.write("".join("%d %d %d\n" % c for c in colors))


def variant_base(name):
    """(kind, base dir) for a variant tileset dir name, or None."""
    if name in VARIANTS:
        kind, base, _, _ = VARIANTS[name]
        return kind, base
    return None


def base_struct(base_suffix):
    text = open(os.path.join(ROOT, "src/data/tilesets/headers.h")).read()
    m = re.search(r"const struct Tileset gTileset_%s =\s*\{(.*?)\};" % base_suffix, text, re.S)
    if not m:
        sys.exit(f"gTileset_{base_suffix} not found in headers.h")
    return m.group(1)


def main():
    header = [GENERATED, "// Strata era variants of stock tilesets: same tiles and metatiles, new palettes.", ""]
    for variant, (kind, base, base_suffix, transform) in VARIANTS.items():
        src = os.path.join(ROOT, "data/tilesets", kind, base, "palettes")
        dst = os.path.join(ROOT, "data/tilesets", kind, variant, "palettes")
        os.makedirs(dst, exist_ok=True)
        for fname in sorted(os.listdir(src)):
            if fname.endswith(".pal"):
                colors = read_pal(os.path.join(src, fname))
                # Color 0 is transparent; keep it so nothing else changes.
                out = colors[:1] + [TRANSFORMS[transform](*c) for c in colors[1:]]
                write_pal(os.path.join(dst, fname), out)

        suffix = symbol_suffix(variant)
        header.append(f"const u16 ALIGNED(4) gTilesetPalettes_{suffix}[][16] =")
        header.append("{")
        for i in range(16):
            header.append(f'    INCGFX_U16("data/tilesets/{kind}/{variant}/palettes/{i:02}.pal", ".gbapal"),')
        header.append("};")
        header.append("")
        body = base_struct(base_suffix).replace(f"gTilesetPalettes_{base_suffix}", f"gTilesetPalettes_{suffix}")
        header.append(f"const struct Tileset gTileset_{suffix} =")
        header.append("{" + body.rstrip() + "\n};")
        header.append("")
        print("wrote", variant)

    with open(os.path.join(ROOT, "src/data/tilesets/strata_headers.h"), "w") as f:
        f.write("\n".join(header))


if __name__ == "__main__":
    main()
