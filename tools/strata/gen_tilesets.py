def symbol_suffix(variant):
    return "".join(part.capitalize() for part in variant.split("_"))


def read_pal(path):
    lines = open(path).read().split()
    count = int(lines[2])
    return [tuple(int(v) for v in lines[3 + i * 3:6 + i * 3]) for i in range(count)]


def write_pal(path, colors):
    with open(path, "w", newline="\r\n") as f:
        f.write("JASC-PAL\n0100\n%d\n" % len(colors))
        f.write("".join("%d %d %d\n" % tuple(c) for c in colors))


def variant_base(name):
    """(kind, base dir) for a variant tileset dir name, or None."""
    if name in VARIANTS:
        kind, base = VARIANTS[name][:2]
        return kind, base
    return None


def base_struct(base_suffix):
    text = open(os.path.join(ROOT, "src/data/tilesets/headers.h")).read()
    m = re.search(r"const struct Tileset gTileset_%s =\s*\{(.*?)\};" % base_suffix, text, re.S)
    if not m:
        sys.exit(f"gTileset_{base_suffix} not found in headers.h")
    return m.group(1)


def base_tiles_args(base_suffix):
    """The INCGFX arguments after the path of gTilesetTiles_<base> (compression, -num_tiles)."""
    for rel in ("src/graphics.c", "src/data/tilesets/graphics.h"):
        text = open(os.path.join(ROOT, rel)).read()
        m = re.search(r'gTilesetTiles_%s\[\] = INCGFX_U32\("[^"]+"(.*?)\);' % base_suffix, text)
        if m:
            return m.group(1)
    sys.exit(f"gTilesetTiles_{base_suffix} not found")


def variant_colors(colors, transform, ground):
    """A palette of a variant: the ground's lawn swap, then the era transform. Colour 0
    of each 16-colour bank (transparent / backdrop) never changes."""
    if ground:
        colors = gen_era_tiles.remap_ground(colors, ground)
    if transform:
        colors = [c if i % 16 == 0 else TRANSFORMS[transform](*c) for i, c in enumerate(colors)]
    return colors


