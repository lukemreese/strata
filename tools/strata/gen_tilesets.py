#!/usr/bin/env python3
"""Generate era variants of stock tilesets for Strata, and the era art outside them.

Usage (from the repo root):  python3 tools/strata/gen_tilesets.py

A variant reuses its base tileset's metatiles and swaps the palettes, so a map can show
the same kind of place in a different climate. Variants with a `ground` (the eras before
grasslands, see gen_era_tiles.py) also get their own tiles: the Hoenn tall grass, long
grass and lawn redrawn as that era's undergrowth and ground, and the lawn colours swapped
for the era's ground in every palette. The metatile behaviours don't change, so wild
encounters still come from the "tall grass".
Writes data/tilesets/<kind>/<variant>/palettes/*.pal (and tiles.png) and the C definitions
in src/data/tilesets/strata_headers.h (copied from the base's struct in headers.h).

The same era transforms (and grounds) are applied to the outdoor battle-background
palettes and the grass field-effect palette; ground eras also get their own grass battle
backgrounds (platform tiles and entry animation) and grass overlay sprites
(graphics/battle_environment/strata/, graphics/field_effects/{palettes,pics}/strata/,
src/data/strata_era_art.h, read by src/strata_art.c).

    python3 tools/strata/gen_tilesets.py --preview DIR   renders before/after PNGs
    python3 tools/strata/gen_era_tiles.py --preview DIR  the era ground cover
"""

