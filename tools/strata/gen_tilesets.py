def clamp(*rgb):
    return tuple(max(0, min(255, round(c))) for c in rgb)


def lum(r, g, b):
    return 0.30 * r + 0.59 * g + 0.11 * b


def is_green(r, g, b):
    return g > r and g > b


def impact_winter(r, g, b):
    """A year after the impact: soot-darkened and ash-covered. Greens lose
    almost all of their colour."""
    l = lum(r, g, b)
    keep = 0.25 if is_green(r, g, b) else 0.35
    r, g, b = (l + (c - l) * keep for c in (r, g, b))
    return clamp(r * 0.72 + 10, g * 0.70 + 6, b * 0.70 + 4)


def petm(r, g, b):
    """PETM hothouse: warm light, reddened soils, olive vegetation."""
    if is_green(r, g, b):
        r, g, b = r * 1.10 + 12, g * 0.95, b * 0.75
    else:
        r, g, b = r * 1.10 + 8, g * 0.95, b * 0.85
    return clamp(r, g, b)


def oligocene(r, g, b):
    """After the Eocene-Oligocene cooling: drier, paler, yellowed grass."""
    l = lum(r, g, b)
    if is_green(r, g, b):
        r, g, b = r * 1.15 + 18, g * 0.98 + 4, b * 0.70
    r, g, b = (l + (c - l) * 0.80 for c in (r, g, b))
    return clamp(r + 6, g + 4, b)


def ice_age(r, g, b):
    """Glacial steppe: cold light, frost-pale, blue-shifted."""
    l = lum(r, g, b)
    r, g, b = (l + (c - l) * 0.45 for c in (r, g, b))
    return clamp(r * 0.85 + 34, g * 0.90 + 36, b * 0.95 + 52)


def late_glacial(r, g, b):
    """The Colby coda, ~13 ka: the ice is going. Less frost than ice_age (a small cool lift
    instead of its big one, colour kept), greens turned to muted olive-brown tundra and
    steppe, light still cool."""
    l = lum(r, g, b)
    if is_green(r, g, b):
        # Pale greens (the battle sky) keep their coolness: the olive shift fades out above lum 140.
        k = 1.0 if l < 140 else max(0.15, 1.0 - (l - 140) / 70.0)
        r, g, b = (c + (n - c) * k for c, n in zip((r, g, b), (r * 1.16 + 16, g * 0.90, b * 0.68)))
    r, g, b = (l + (c - l) * 0.72 for c in (r, g, b))
    return clamp(r * 0.92 + 12, g * 0.94 + 14, b * 0.97 + 26)


def prairie(r, g, b):
    """Present-day Montana prairie: the Hoenn greens dried to sage and straw, the rest
    (rock, soil, roofs, water) nearly untouched."""
    if is_green(r, g, b):
        l = lum(r, g, b)
        r, g, b = r * 1.12 + 14, g * 0.96 + 2, b * 0.70
        r, g, b = (l + (c - l) * 0.80 for c in (r, g, b))
        return clamp(r, g, b)
    return clamp(r + 3, g + 2, b - 2)


