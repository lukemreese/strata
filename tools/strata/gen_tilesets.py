def transform_pal(colors, transform):
    """Applies an era transform to every 16-colour bank, keeping each bank's
    colour 0 (transparent / backdrop) unchanged."""
    return [c if i % 16 == 0 else TRANSFORMS[transform](*c) for i, c in enumerate(colors)]


def gen_era_art():
    """Writes the era palettes and art for battle backgrounds and the grass overlays,
    and src/data/strata_era_art.h, which strata_art.c includes."""
    out = [GENERATED, "// Era variants of the battle backgrounds and the grass field effects.", ""]
    for name, transform, ground in art_sets():
        suffix = symbol_suffix(name)
        dst = f"graphics/battle_environment/strata/{name}"
        os.makedirs(os.path.join(ROOT, dst), exist_ok=True)
        tpal = (lambda c, t=transform: transform_pal(c, t)) if transform else (lambda c: c)
        art = gen_era_tiles.write_era_art(ground, tpal, os.path.join(ROOT, dst),
                                          os.path.join(ROOT, "graphics/field_effects/pics/strata")) if ground else {}

        rows = []
        for env, envdir in BATTLE_ENVS.items():
            if ground and env in GRASS_ENVS:
                colors = art[f"{envdir}_pal"]
            elif ground and envdir == "plain":
                colors = art["plain_pal"]
            elif transform:
                colors = transform_pal(read_pal(os.path.join(ROOT, "graphics/battle_environment", envdir, "palette.pal")), transform)
            else:
                continue
            pal = f"{dst}/{envdir}.pal"
            write_pal(os.path.join(ROOT, pal), colors)
            sym = f"sBattleEnvPal_{suffix}_{symbol_suffix(envdir)}"
            out.append(f'static const u16 {sym}[] = INCGFX_U16("{pal}", ".gbapal");')
            rows.append(f"    [{env}] = {sym},")
        out.append("")
        out.append(f"static const u16 *const sBattleEnvPals_{suffix}[BATTLE_ENVIRONMENT_COUNT] =")
        out += ["{"] + rows + ["};", ""]

        fields = [f".battleEnvPalettes = sBattleEnvPals_{suffix}"]
        fe_dir = "graphics/field_effects/palettes/strata"
        os.makedirs(os.path.join(ROOT, fe_dir), exist_ok=True)
        fe_pal = f"{fe_dir}/general_1_{name}.pal"
        colors = art["fe_pal"] if ground else transform_pal(read_pal(os.path.join(ROOT, FIELD_EFFECT_PAL)), transform)
        write_pal(os.path.join(ROOT, fe_pal), colors)
        out.append(f'static const u16 sFieldEffectPal1_{suffix}[] = INCGFX_U16("{fe_pal}", ".gbapal");')
        out.append(f"static const struct SpritePalette sFieldEffectSpritePal1_{suffix} = "
                   f"{{sFieldEffectPal1_{suffix}, FLDEFF_PAL_TAG_GENERAL_1}};")
        out.append("")
        fields.append(f".fieldEffectPal1 = &sFieldEffectSpritePal1_{suffix}")

        if ground:
            for what, key, field in (("Tiles", "tiles", "battleEnvTiles"), ("AnimTiles", "anim", "battleEnvAnimTiles")):
                rows = []
                for env, envdir in GRASS_ENVS.items():
                    rel = os.path.relpath(art[f"{envdir}_{key}"], ROOT)
                    sym = f"sBattleEnv{what}_{suffix}_{symbol_suffix(envdir)}"
                    out.append(f'static const u32 {sym}[] = INCGFX_U32("{rel}", ".4bpp.smol");')
                    rows.append(f"    [{env}] = {sym},")
                out.append(f"static const u32 *const sBattleEnv{what}_{suffix}[BATTLE_ENVIRONMENT_COUNT] =")
                out += ["{"] + rows + ["};", ""]
                fields.append(f".{field} = sBattleEnv{what}_{suffix}")
            for kind, field in (("tall", "tallGrassPics"), ("long", "longGrassPics")):
                rel = os.path.relpath(art[f"fe_{kind}"], ROOT)
                sym = f"sFieldEffectPic_{kind.capitalize()}Grass_{suffix}"
                out.append(f'static const u32 {sym}[] = INCGFX_U32("{rel}", ".4bpp", "-mwidth 2 -mheight 2");')
                out.append(f"static const struct SpriteFrameImage sPicTable_{kind.capitalize()}Grass_{suffix}[] = "
                           f"{{ overworld_ascending_frames({sym}, 2, 2), }};")
                fields.append(f".{field} = sPicTable_{kind.capitalize()}Grass_{suffix}")
            out.append("")
        out.append(f"static const struct StrataEraArt sStrataArt_{suffix} =")
        out += ["{"] + [f"    {f}," for f in fields] + ["};", ""]
        print("wrote era art", name)

    out.append("static const struct StrataEraArt *const sStrataEraArt[ERA_COUNT] =")
    out += ["{"] + [f"    [{era}] = &sStrataArt_{symbol_suffix(name)}," for era, (name, _, _) in ERA_ART.items()] + ["};", ""]
    out.append("// Per-map art, checked before the era's (MAP_ART in gen_tilesets.py).")
    out.append("static const struct StrataMapArt sStrataMapArt[] =")
    out += ["{"] + [f"    {{ {m}, &sStrataArt_{symbol_suffix(name)} }}," for m, (name, _, _) in MAP_ART.items()] + ["};"]
    with open(os.path.join(ROOT, "src/data/strata_era_art.h"), "w") as f:
        f.write("\n".join(out) + "\n")


def render_battle_bg(envdir, colors, scale=1, tiles=None):
    """RGB rows of a battle background (tiles.png + map.bin) in the given 48-colour palette.
    `tiles` overrides the tile sheet (an era's redrawn platforms)."""
    from maprender import read_png
    w, h, idx = read_png(tiles or os.path.join(ROOT, "graphics/battle_environment", envdir, "tiles.png"))
    tiles_per_row = w // 8
    data = open(os.path.join(ROOT, "graphics/battle_environment", envdir, "map.bin"), "rb").read()
    cols, rows = 32, 20  # the visible 240x160 part of the 32x32 screen
    img = [[(0, 0, 0)] * (cols * 8 * scale) for _ in range(rows * 8 * scale)]
    for ty in range(rows):
        for tx in range(cols):
            e = data[(ty * 32 + tx) * 2] | data[(ty * 32 + tx) * 2 + 1] << 8
            tile, hf, vf, pal = e & 0x3FF, e >> 10 & 1, e >> 11 & 1, e >> 12
            bank = (pal - 2) % 3  # battle BG palettes are loaded at BG palette 2
            sx, sy = (tile % tiles_per_row) * 8, (tile // tiles_per_row) * 8
            for y in range(8):
                for x in range(8):
                    py, px = sy + (7 - y if vf else y), sx + (7 - x if hf else x)
                    c = colors[bank * 16 + idx[py][px]] if py < h else (0, 0, 0)
                    for yy in range(scale):
                        for xx in range(scale):
                            img[(ty * 8 + y) * scale + yy][(tx * 8 + x) * scale + xx] = c
    return img


def preview(outdir):
    """Writes battle_bg_<env>.png: the stock background above each era variant."""
    from maprender import write_png
    os.makedirs(outdir, exist_ok=True)
    for envdir in ("tall_grass", "long_grass", "water", "sand", "cave"):
        stock = read_pal(os.path.join(ROOT, "graphics/battle_environment", envdir, "palette.pal"))
        panels = [render_battle_bg(envdir, stock)]
        names = []
        for name, transform, ground in art_sets():
            pal = os.path.join(ROOT, "graphics/battle_environment/strata", name, f"{envdir}.pal")
            if not os.path.exists(pal):
                continue
            tiles = os.path.join(ROOT, "graphics/battle_environment/strata", name, f"{envdir}_tiles.png")
            panels.append(render_battle_bg(envdir, read_pal(pal), tiles=tiles if os.path.exists(tiles) else None))
            names.append(name)
        img = [row for p in panels for row in p + [[(255, 255, 255)] * len(p[0])] * 2]
        path = os.path.join(outdir, f"battle_bg_{envdir}.png")
        write_png(path, len(img[0]), len(img), img)
        print("wrote", path, "(stock, then", ", ".join(names) + ")")

    # The tall-grass field effect (5 frames of 16x16) on its era palettes, at 4x.
    from maprender import read_png
    stock = read_pal(os.path.join(ROOT, FIELD_EFFECT_PAL))
    sheets = [("graphics/field_effects/pics/tall_grass.png", stock)]
    for name, transform, ground in art_sets():
        pic = f"graphics/field_effects/pics/strata/tall_grass_{ground}.png" if ground else "graphics/field_effects/pics/tall_grass.png"
        sheets.append((pic, read_pal(os.path.join(ROOT, f"graphics/field_effects/palettes/strata/general_1_{name}.pal"))))
    s, bg = 4, (96, 96, 96)
    w, h, _ = read_png(os.path.join(ROOT, sheets[0][0]))
    img = [[bg] * (w * s) for _ in range(h * len(sheets) * s)]
    for n, (pic, pal) in enumerate(sheets):
        _, _, idx = read_png(os.path.join(ROOT, pic))
        for y in range(h * s):
            for x in range(w * s):
                i = idx[y // s][x // s]
                if i:
                    img[n * h * s + y][x] = pal[i]
    path = os.path.join(outdir, "tall_grass_overlay.png")
    write_png(path, len(img[0]), len(img), img)
    print("wrote", path)


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--preview":
        preview(sys.argv[2])
        return
    gen_era_art()
    header = [GENERATED, "// Strata era variants of stock tilesets: same metatiles, new palettes and, for the",
              "// eras before grasslands, their own ground cover tiles (gen_era_tiles.py).", ""]
    for variant, (kind, base, base_suffix, transform, ground) in VARIANTS.items():
        src = os.path.join(ROOT, "data/tilesets", kind, base, "palettes")
        vdir = os.path.join(ROOT, "data/tilesets", kind, variant)
        dst = os.path.join(vdir, "palettes")
        os.makedirs(dst, exist_ok=True)
        for fname in sorted(os.listdir(src)):
            if fname.endswith(".pal"):
                colors = read_pal(os.path.join(src, fname))
                # Color 0 is transparent; keep it so nothing else changes.
                out = colors[:1] + variant_colors(colors, transform, ground)[1:]
                write_pal(os.path.join(dst, fname), out)

        suffix = symbol_suffix(variant)
        tiles_png = os.path.join(vdir, "tiles.png")
        own_tiles = bool(ground) and gen_era_tiles.write_variant_tiles(kind, base, ground, tiles_png)
        if not own_tiles and os.path.exists(tiles_png):
            os.remove(tiles_png)
        if own_tiles:
            header.append(f'const u32 gTilesetTiles_{suffix}[] = INCGFX_U32("data/tilesets/{kind}/{variant}/tiles.png"'
                          f"{base_tiles_args(base_suffix)});")
            header.append("")
        header.append(f"const u16 ALIGNED(4) gTilesetPalettes_{suffix}[][16] =")
        header.append("{")
        for i in range(16):
            header.append(f'    INCGFX_U16("data/tilesets/{kind}/{variant}/palettes/{i:02}.pal", ".gbapal"),')
        header.append("};")
        header.append("")
        body = base_struct(base_suffix).replace(f"gTilesetPalettes_{base_suffix}", f"gTilesetPalettes_{suffix}")
        if own_tiles:
            body = body.replace(f"gTilesetTiles_{base_suffix},", f"gTilesetTiles_{suffix},")
        header.append(f"const struct Tileset gTileset_{suffix} =")
        header.append("{" + body.rstrip() + "\n};")
        header.append("")
        print("wrote", variant, "(tiles + palettes)" if own_tiles else "(palettes)")

    with open(os.path.join(ROOT, "src/data/tilesets/strata_headers.h"), "w") as f:
        f.write("\n".join(header))


